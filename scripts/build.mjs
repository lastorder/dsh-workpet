/**
 * Shared build for every package in this workspace.
 *
 * A package has up to three outputs, each produced only when its source exists:
 * - `src/index.ts`          → `lib/index.js`  (Host half, ESM, loaded by the Loader row)
 * - `src/client/index.ts(x)` → `lib/client.js` (Client half, classic script that calls
 *   `window.__ModuleLoader__.load({ id, factory })`; `react` arrives through the
 *   factory's `require`, so it is never bundled)
 * - `tsconfig.build.json`   → `lib/types/**` (declarations for type-only consumers)
 *
 * Usage: `node scripts/build.mjs [package-dir ...]`; no argument builds every package.
 */
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, rmSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** Module specifiers the DSH browser module table provides to every Client half. */
const CLIENT_EXTERNALS = ['react', 'react/jsx-runtime', 'react-dom']

/**
 * Build one Client half in the `__ModuleLoader__` factory format.
 * @param {string} id - package name; the module table keys the factory by it.
 * @param {string} entry - absolute entry file.
 * @param {string} outfile - absolute output file.
 */
async function buildClient(id, entry, outfile) {
  await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: CLIENT_EXTERNALS,
    legalComments: 'none',
    banner: {
      js: [
        `// ${id} — generated by scripts/build.mjs; edit src/client instead.`,
        'window.__ModuleLoader__.load({',
        `  id: ${JSON.stringify(id)},`,
        '  factory: (require) => {',
        '    var module = { exports: {} };',
        '    var exports = module.exports;',
      ].join('\n'),
    },
    footer: { js: '    return module.exports;\n  },\n});' },
  })
}

/**
 * Build one Host half: a small ESM module the Loader imports.
 * @param {string} entry - absolute entry file.
 * @param {string} outfile - absolute output file.
 */
async function buildHost(entry, outfile) {
  await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    legalComments: 'none',
  })
}

/** @param {string} dir - absolute package directory. */
async function buildPackage(dir) {
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  rmSync(join(dir, 'lib'), { recursive: true, force: true })
  const outputs = []
  const host = join(dir, 'src/index.ts')
  if (existsSync(host)) {
    await buildHost(host, join(dir, 'lib/index.js'))
    outputs.push('lib/index.js')
  }
  const client = ['src/client/index.ts', 'src/client/index.tsx'].map(p => join(dir, p)).find(existsSync)
  if (client !== undefined) {
    await buildClient(manifest.name, client, join(dir, 'lib/client.js'))
    outputs.push('lib/client.js')
  }
  const declarations = join(dir, 'tsconfig.build.json')
  if (existsSync(declarations)) {
    execFileSync(process.execPath, [join(root, 'node_modules/typescript/bin/tsc'), '-p', declarations], { stdio: 'inherit' })
    outputs.push('lib/types')
  }
  console.log(`built ${manifest.name}: ${outputs.join(', ')}`)
}

function allPackages() {
  const base = join(root, 'packages')
  return readdirSync(base, { withFileTypes: true })
    .filter(group => group.isDirectory())
    .flatMap(group => readdirSync(join(base, group.name), { withFileTypes: true })
      .filter(pkg => pkg.isDirectory() && existsSync(join(base, group.name, pkg.name, 'package.json')))
      .map(pkg => join(base, group.name, pkg.name)))
}

const targets = process.argv.length > 2 ? process.argv.slice(2).map(p => resolve(p)) : allPackages()
for (const dir of targets) {
  try {
    await buildPackage(dir)
  } catch (error) {
    console.error(`build failed for ${relative(root, dir)}`)
    throw error
  }
}
